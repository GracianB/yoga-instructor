import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

test('PRESENCIA online pages are deployed, bilingual and privacy-first', () => {
  const es = readFileSync('clases-online.html','utf8');
  const en = readFileSync('clases-online-en.html','utf8');
  const css = readFileSync('presencia-online.css','utf8');
  const home = readFileSync('index.html','utf8');
  const build = readFileSync('tools/build.mjs','utf8');
  const sitemap = readFileSync('sitemap.xml','utf8');
  const check=(page, lang, other, contactId)=>{
    assert.match(page,new RegExp('<html lang="'+lang+'">'));
    assert.ok(page.includes('href="./presencia-online.css?v=1"'));
    assert.ok(page.includes('href="./clases-online-'+other+'.html"') || (lang==='en' && page.includes('href="./clases-online.html"')));
    assert.ok(page.includes('mailto:gracianbaenagonzalez@gmail.com'));
    assert.ok(page.includes('href="https://calendar.app.google/n99psBFktwYyoAWi9"'));
    assert.ok(page.includes('id="'+contactId+'"'));
    assert.doesNotMatch(page,/<script\b/i);
    assert.doesNotMatch(page,/<form\b/i);
    assert.doesNotMatch(page,/type="tel"|itemprop="telephone"/);
    assert.doesNotMatch(page,/<style\b/i);
    assert.ok(!/29\s+de\s+noviembre|November\s+29/i.test(page),'Never invent a workshop date');
    assert.ok(!/>15\s*€</.test(page),'Do not publish draft price');
  };
  assert.match(es, /<main id="contenido">/);
  assert.match(en, /<main id="content">/);
  assert.match(es, /60 minutos/);
  assert.match(en, /60 minutes/);
  assert.match(es, /Duración y calendario/);
  assert.match(es, /Precio y condiciones/);
  assert.match(en, /Price and conditions/);
  assert.match(es, /Se concretan antes de confirmar/);
  assert.match(en, /Dates and times are agreed individually/);
  assert.match(es, /<a class="skip" href="#contenido">/);
  assert.match(en, /<a class="skip" href="#content">/);
  check(es,'es','en','contacto');
  check(en,'en','es','contact');
  assert.match(css, /prefers-reduced-motion/);
  assert.match(css, /focus-visible/);
  assert.match(css, /@media\(max-width:520px\)/);
  assert.match(home, /href="\.\/clases-online\.html"/);
  assert.match(home, /href="\.\/clases-online-en\.html"/);
  assert.match(build, /'clases-online\.html'/);
  assert.match(build, /'clases-online-en\.html'/);
  assert.match(build, /'presencia-online\.css'/);
  assert.match(sitemap, /clases-online\.html/);
  assert.match(sitemap, /clases-online-en\.html/);
});
