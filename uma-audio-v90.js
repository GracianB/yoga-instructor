/* V90 · Optional meditation reading and ambient sound via the existing audio bus.
 * Voice begins only after explicit opt-in, uses browser speech synthesis only,
 * and never calls remote APIs from this application. Browser voice behavior
 * depends on OS/platform; no offline-only guarantee is made. */
(()=>{
"use strict";
const root=document.getElementById("instructor-flow"),stage=root?.querySelector("#studio-guided");
const ritual=stage?.querySelector(".v89-ritual"),bus=window.YOGA_AUDIO_BUS;
if(!root||!stage||!ritual||!bus)return;
const synth=window.speechSynthesis;
const voiceAvailable=Boolean(synth&&typeof window.SpeechSynthesisUtterance==="function");
const panel=document.createElement("section");
panel.className="v90-sound";
panel.setAttribute("aria-labelledby","v90-title");panel.hidden=true;
panel.innerHTML='<div class="v90-header"><div><span class="v90-kicker"></span><h4 id="v90-title"></h4></div><p class="v90-description"></p></div>'+
'<div class="v90-sound-options" role="group"><button type="button" data-v90-action="silence" aria-pressed="true"></button>'+
'<button type="button" data-v90-action="music" aria-pressed="false"></button>'+
'<button type="button" data-v90-action="pick"></button>'+
'<input type="file" class="v90-file" accept="audio/*,.mp3" hidden></div>'+
'<div class="v90-voice"><div><strong class="v90-voice-title"></strong><p class="v90-voice-note"></p></div>'+
'<button type="button" data-v90-action="voice" aria-pressed="false"></button></div>'+
'<p class="v90-status" role="status" aria-live="polite"></p>';
ritual.after(panel);
const file=panel.querySelector(".v90-file"),status=panel.querySelector(".v90-status");
const copy={
es:{kicker:"UMA · SILENCIO Y SONIDO",title:"Escucha solo si quieres.",
 description:"Usa la canción integrada, un archivo tuyo o el silencio. Sin sonidos automáticos.",
 silence:"Silencio total",music:"Música · activar",musicOff:"Música · pausar",
 pick:"Elegir audio local",voiceTitle:"Acompañamiento de voz",
 voiceNote:"La voz la genera el navegador. Su disponibilidad y el tratamiento de voz dependen del sistema y sus ajustes.",
 voiceOn:"Activar voz",voiceOff:"Desactivar voz",unsupported:"Voz no disponible en este navegador.",
 ready:"Voz activada. Comienza la práctica para escuchar la guía.",off:"Voz desactivada.",
 muted:"La meditación en silencio no incluye indicaciones habladas.",
 failed:"No se pudo iniciar la voz. Sigue leyendo la guía en pantalla.",
 fileSelected:"Archivo preparado. Pulsa Música para escucharlo.",soundSilent:"Silencio seleccionado.",
 start:"Música solicitada.",stop:"Música detenida."},
en:{kicker:"UMA · SILENCE AND SOUND",title:"Listen only if you want.",
 description:"Use the included track, your own audio file or silence. Never any surprise playback.",
 silence:"Complete silence",music:"Music · play",musicOff:"Music · pause",
 pick:"Choose local audio",voiceTitle:"Optional spoken guidance",
 voiceNote:"Speech is generated by your browser. Availability and speech data handling depend on your operating system and voice settings.",
 voiceOn:"Enable voice",voiceOff:"Disable voice",unsupported:"Voice is not available in this browser.",
 ready:"Voice enabled. Begin the session to hear guidance.",off:"Voice disabled.",
 muted:"Silent meditation does not include spoken instructions.",
 failed:"Speech could not start. The written guide remains available.",
 fileSelected:"Audio selected. Press Music to play it.",soundSilent:"Silence selected.",
 start:"Music requested.",stop:"Music stopped."}
};
const locale=()=>document.documentElement.lang==="en"?"en":"es";
let voiceEnabled=false,spokenKey=null,lastMessage="";
const sayStatus=message=>{lastMessage=message;status.textContent=message};
function cancelVoice(){if(voiceAvailable)try{synth.cancel()}catch(_){}}
function readGuidance(){
 if(!voiceEnabled||!voiceAvailable||document.hidden||
  root.dataset.studioMode!=="meditation"||stage.dataset.meditationStyle==="silent"||
  stage.dataset.studioStatus!=="running")return;
 const phase=stage.dataset.meditationStep||"prepare";
 const focus=stage.dataset.meditationFocus||"breath";
 const key=locale()+":"+focus+":"+phase;
 if(key===spokenKey)return;
 spokenKey=key;
 if(!bus.audio.paused)bus.stop(); // One intentional audio source at a time.
 cancelVoice();
 const cue=window.YOGA_MEDITATION_RITUAL_V89?.cue(focus,phase,locale());
 if(!cue)return;
 try{
  const utterance=new window.SpeechSynthesisUtterance(cue.body);
  utterance.lang=locale()==="en"?"en-GB":"es-ES";
  utterance.rate=.9;utterance.volume=.75;
  synth.speak(utterance);
 }catch(_){voiceEnabled=false;cancelVoice();sayStatus(copy[locale()].failed);paint()}
}
function paint(){
 const t=copy[locale()];
 panel.hidden=root.dataset.studioMode!=="meditation";
 panel.querySelector(".v90-kicker").textContent=t.kicker;
 panel.querySelector("#v90-title").textContent=t.title;
 panel.querySelector(".v90-description").textContent=t.description;
 panel.querySelector(".v90-voice-title").textContent=t.voiceTitle;
 panel.querySelector(".v90-voice-note").textContent=voiceAvailable?t.voiceNote:t.unsupported;
 const active=!bus.audio.paused&&bus.owner==="meditation";
 const buttons={};
 for(const b of panel.querySelectorAll("[data-v90-action]"))buttons[b.dataset.v90Action]=b;
 buttons.silence.textContent=t.silence;
 buttons.silence.setAttribute("aria-pressed",String(!active&&!voiceEnabled));
 buttons.music.textContent=active?t.musicOff:t.music;
 buttons.music.setAttribute("aria-pressed",String(active));
 buttons.pick.textContent=t.pick;
 buttons.voice.textContent=voiceEnabled?t.voiceOff:t.voiceOn;
 buttons.voice.disabled=!voiceAvailable||stage.dataset.meditationStyle==="silent";
 buttons.voice.setAttribute("aria-pressed",String(voiceEnabled));
 panel.querySelector(".v90-sound-options").setAttribute("aria-label",t.kicker);
 file.setAttribute("aria-label",t.pick);
 if(lastMessage)status.textContent=lastMessage;
}
async function toggleMusic(){
 if(!bus.audio.paused&&bus.owner==="meditation"){bus.stop();sayStatus(copy[locale()].stop)}
 else{
  if(voiceEnabled){voiceEnabled=false;cancelVoice();spokenKey=null}
  const ok=await bus.play("meditation");
  sayStatus(ok?copy[locale()].start:copy[locale()].stop);
 }
 paint();
}
panel.addEventListener("click",event=>{
 const action=event.target.closest("[data-v90-action]")?.dataset.v90Action;
 if(!action)return;
 if(action==="pick"){file.click();return}
 if(action==="silence"){
  voiceEnabled=false;spokenKey=null;cancelVoice();bus.stop();
  sayStatus(copy[locale()].soundSilent);paint();return;
 }
 if(action==="music"){void toggleMusic();return}
 if(action==="voice"&&voiceAvailable&&stage.dataset.meditationStyle!=="silent"){
  voiceEnabled=!voiceEnabled;
  spokenKey=null;
  if(voiceEnabled){if(!bus.audio.paused)bus.stop();sayStatus(copy[locale()].ready);readGuidance()}
  else {cancelVoice();sayStatus(copy[locale()].off)}
  paint();
 }
});
file.addEventListener("change",()=>{
 if(bus.selectFile(file.files?.[0]))sayStatus(copy[locale()].fileSelected);
 paint();
});
window.addEventListener("yoga:audiochange",paint);
const observe=new MutationObserver(changes=>{
 if(changes.some(c=>c.attributeName==="data-studio-mode"||c.attributeName==="lang"))paint();
 if(root.dataset.studioMode!=="meditation"){
  if(voiceEnabled){voiceEnabled=false;spokenKey=null;cancelVoice()}
  if(bus.owner==="meditation")bus.stop();
  paint();return;
 }
 if(stage.dataset.meditationStyle==="silent"){
  if(voiceEnabled){voiceEnabled=false;spokenKey=null;cancelVoice();sayStatus(copy[locale()].muted)}
 }
 if(stage.dataset.studioStatus!=="running")cancelVoice();
 readGuidance();paint();
});
observe.observe(stage,{attributes:true,attributeFilter:["data-meditation-step","data-meditation-focus","data-meditation-style","data-studio-status"]});
observe.observe(root,{attributes:true,attributeFilter:["data-studio-mode"]});
observe.observe(document.documentElement,{attributes:true,attributeFilter:["lang"]});
document.addEventListener("visibilitychange",()=>{
 if(document.hidden){voiceEnabled=false;spokenKey=null;cancelVoice();if(bus.owner==="meditation")bus.stop();paint()}
});
window.addEventListener("pagehide",()=>{
 observe.disconnect();cancelVoice();if(bus.owner==="meditation")bus.stop();
 window.removeEventListener("yoga:audiochange",paint);
},{once:true});
paint();
})();
